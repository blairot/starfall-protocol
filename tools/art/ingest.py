"""Bring painted art from art/incoming/ into the game.

Cards:     centre-crop to 16:10, 960x600 WebP  -> art/cards/<id>.webp
Portraits: centre-crop to square, 512x512 WebP -> art/portraits/<file>.webp
Part 2 (art/manifest2.json): packs 640x960, card back 400x600, wide scenes
1440x960 -> art/extra/ (one size: phones show these one at a time); the app
icon -> icons/*.png.
Then rewrites js/painted.js, which tells illustrations.js which plates have
painted art (everything else keeps its code-drawn art).

Run from the repo root:  python tools/art/ingest.py   (needs Pillow)
"""
import json, os, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ART = os.path.join(ROOT, 'art')


def crop_to(img, ratio):
    w, h = img.size
    if w / h > ratio:
        nw = round(h * ratio); x = (w - nw) // 2
        return img.crop((x, 0, x + nw, h))
    nh = round(w / ratio); y = (h - nh) // 2
    return img.crop((0, y, w, y + nh))


def main():
    manifest = json.load(open(os.path.join(ART, 'manifest.json'), encoding='utf8'))
    incoming = os.path.join(ART, 'incoming')
    files = {f.lower(): f for f in os.listdir(incoming)} if os.path.isdir(incoming) else {}
    os.makedirs(os.path.join(ART, 'cards'), exist_ok=True); os.makedirs(os.path.join(ART, 'portraits'), exist_ok=True); os.makedirs(os.path.join(ART, 'cards-sm'), exist_ok=True)
    cards, portraits, missing, made = [], {}, [], 0
    for e in manifest:
        stem = os.path.splitext(e['file'])[0]
        src = next((files[k] for k in (stem + '.png', stem + '.webp', stem + '.jpg', stem + '.jpeg') if k in files), None)
        sub, size = ('cards', (960, 600)) if e['kind'] == 'card' else ('portraits', (512, 512))
        out = os.path.join(ART, sub, stem + '.webp')
        if src:
            sp = os.path.join(incoming, src)
            if not os.path.exists(out) or os.path.getmtime(sp) > os.path.getmtime(out):
                img = Image.open(sp).convert('RGB')
                img = crop_to(img, size[0] / size[1]).resize(size, Image.LANCZOS)
                img.save(out, 'WEBP', quality=82, method=6)
                if e['kind'] == 'card':   # half-size copy for phones (a quarter of the decode memory)
                    img.resize((480, 300), Image.LANCZOS).save(os.path.join(ART, 'cards-sm', stem + '.webp'), 'WEBP', quality=80, method=6)
                made += 1
        sm = os.path.join(ART, 'cards-sm', stem + '.webp')
        if e['kind'] == 'card' and os.path.exists(out) and not os.path.exists(sm):
            Image.open(out).resize((480, 300), Image.LANCZOS).save(sm, 'WEBP', quality=80, method=6)
        if os.path.exists(out):
            if e['kind'] == 'card': cards.append(e['id'])
            else: portraits[e['id']] = stem
        else:
            missing.append(e['file'])
    extra = ingest_extra(files, incoming)
    with open(os.path.join(ROOT, 'js', 'painted.js'), 'w', encoding='utf8') as fp:
        fp.write("'use strict';\n// Generated by tools/art/ingest.py: plates that have painted art in art/cards and art/portraits.\n")
        fp.write('const PAINTED = ' + json.dumps({'cards': sorted(cards), 'portraits': portraits, 'extra': sorted(extra)}, separators=(',', ':')) + ';\n')
    print(f'{made} converted; painted: {len(cards)} cards, {len(portraits)} portraits; {len(extra)} extras; still code-drawn: {len(missing)}')


EXTRA_SIZE = {'pack': (640, 960), 'cardback': (400, 600)}   # everything else is a wide scene


def ingest_extra(files, incoming):
    """Second pass: packs, cutscene stills, station, sectors, screens, card back, app icon."""
    mp = os.path.join(ART, 'manifest2.json')
    if not os.path.exists(mp): return []
    os.makedirs(os.path.join(ART, 'extra'), exist_ok=True)
    have = []
    for e in json.load(open(mp, encoding='utf8')):
        stem = e['id']
        src = next((files[k] for k in (stem + '.png', stem + '.webp', stem + '.jpg', stem + '.jpeg') if k in files), None)
        if e['kind'] == 'icon':
            if src:
                img = crop_to(Image.open(os.path.join(incoming, src)).convert('RGB'), 1)
                for name, px in (('icon-512', 512), ('maskable-512', 512), ('icon-192', 192), ('apple-touch-icon', 180), ('favicon-32', 32)):
                    img.resize((px, px), Image.LANCZOS).save(os.path.join(ROOT, 'icons', name + '.png'), 'PNG', optimize=True)
                have.append(stem)
            continue
        size = EXTRA_SIZE.get(e['kind'], (1440, 960))
        out = os.path.join(ART, 'extra', stem + '.webp')
        if src:
            sp = os.path.join(incoming, src)
            if not os.path.exists(out) or os.path.getmtime(sp) > os.path.getmtime(out):
                img = crop_to(Image.open(sp).convert('RGB'), size[0] / size[1]).resize(size, Image.LANCZOS)
                img.save(out, 'WEBP', quality=80, method=6)
        if os.path.exists(out): have.append(stem)
    return have


if __name__ == '__main__':
    main()
